interface DealSeed {
  id: string;
  storeId: string;
  mallId: string;
  productIds: readonly string[];
  titleId: string;
  titleEn: string;
  descriptionId: string;
  descriptionEn: string;
  discountId: string;
  discountEn: string;
  imageUrl: string;
  startsAt: string;
  endsAt: string;
  status: DealStatus;
  isFeatured?: boolean;
  isSponsored?: boolean;
}

function createDeal(seed: DealSeed): Deal {
  return {
    id: seed.id,
    storeId: seed.storeId,
    mallId: seed.mallId,
    productIds: seed.productIds,
    title: text(seed.titleId, seed.titleEn),
    description: text(seed.descriptionId, seed.descriptionEn),
    image: image(
      `media-${seed.id}`,
      seed.imageUrl,
      `Visual promo ${seed.titleId}`,
      `${seed.titleEn} promotion visual`,
    ),
    discountLabel: text(seed.discountId, seed.discountEn),
    terms: text(
      'Berlaku selama persediaan masih ada. Syarat berlaku.',
      'Valid while stocks last. Terms apply.',
    ),
    startsAt: seed.startsAt,
    endsAt: seed.endsAt,
    status: seed.status,
    isFeatured: seed.isFeatured ?? false,
    isSponsored: seed.isSponsored ?? false,
    ...timestamps(),
  };
}

